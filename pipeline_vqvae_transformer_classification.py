def train(epoch, loader, model, optimizer, scheduler, device, val_loader=None):
    if is_primary():
        loader = tqdm(loader)

    criterion = nn.MSELoss()

    latent_loss_weight = 0.35
    diversity_loss_weight = 0.0001

    mse_sum = 0
    mse_n = 0
    model.train()
    for i, (img, label) in enumerate(loader):
        model.zero_grad()

        img = img.to(device)
        out, latent_loss, diversity_loss, codebook_usage = model(img)
        recon_loss = criterion(out, img)
        latent_loss = latent_loss.mean()
        loss = recon_loss + latent_loss_weight * latent_loss + diversity_loss_weight * diversity_loss
        loss.backward()

        if scheduler is not None:
            scheduler.step()
        optimizer.step()

        part_mse_sum = recon_loss.item() * img.shape[0]
        part_mse_n = img.shape[0]
        comm = {"mse_sum": part_mse_sum, "mse_n": part_mse_n}
        comm = dist.all_gather(comm)

        for part in comm:
            mse_sum += part["mse_sum"]
            mse_n += part["mse_n"]

        if is_primary():
            lr = optimizer.param_groups[0]["lr"]
            loader.set_description(
                (
                    f"epoch: {epoch + 1}; mse: {recon_loss.item():.5f}; "
                    f"latent: {latent_loss.item():.3f}; avg mse: {mse_sum / mse_n:.5f}; "
                    f"lr: {lr:.5f}"
                )
            )
            run["vqvae/train-mse"].log(recon_loss.item())
            run["vqvae/train-latent"].log(latent_loss.item())
            run["vqvae/train-epoch"].log(epoch + 1)
            run["vqvae/train-num_used_codebooks"].log(codebook_usage)

    # ----- Validation pass (optional) -----
    if val_loader is not None:
        model.eval()
        val_mse_sum = 0
        val_mse_n = 0

        vloader = val_loader
        if is_primary():
            vloader = tqdm(val_loader, leave=False, desc="validating")

        with torch.no_grad():
            for img, _ in vloader:
                img = img.to(device)
                out, _, _, _ = model(img)
                recon_loss = criterion(out, img)

                part_mse_sum = recon_loss.item() * img.shape[0]
                part_mse_n = img.shape[0]
                comm = {"mse_sum": part_mse_sum, "mse_n": part_mse_n}
                comm = dist.all_gather(comm)

                for part in comm:
                    val_mse_sum += part["mse_sum"]
                    val_mse_n += part["mse_n"]

                if is_primary():
                    run["vqvae/val-mse_batch"].log(recon_loss.item())

        if is_primary():
            val_mse_avg = val_mse_sum / max(1, val_mse_n)
            run["vqvae/val-mse"].log(val_mse_avg)
            run["vqvae/val-epoch"].log(epoch + 1)

        model.train()


