import torch
from torch import nn


def train(
    epoch,
    loader,
    model,
    optimizer,
    scheduler,
    device,
    val_loader=None,
    num_classes=None,          # optional sanity check for C
    ignore_index=None,         # e.g., -100 if you have padding; else None
    log_every=500,             # how often to LOG (not compute) during val
    grad_clip_norm=None,       # e.g., 1.0 or None
    use_amp=True               # mixed precision on CUDA
):
    """
    inputs:  [B, 400, 74]  (64-d masked vec + 10-d one-hot -> 74)
    labels:  [B, 400]      (class indices in [0..C-1], or ignore_index for padding)
    logits:  [B, 400, C]   (model output)
    """

    # ---- set up ----
    # CE across tokens; ignore padded positions if ignore_index is provided
    criterion = nn.CrossEntropyLoss(ignore_index=ignore_index) if ignore_index is not None else nn.CrossEntropyLoss()

    scaler = torch.cuda.amp.GradScaler(enabled=(use_amp and device.type == "cuda"))

    # ---------- TRAIN ----------
    iterator = tqdm(loader) if is_primary() else loader
    model.train()  # ALL ranks

    for step, (inputs74, labels) in enumerate(iterator, start=1):
        # Move to device
        inputs74 = inputs74.to(device, non_blocking=True)      # [B, 400, 74]
        labels   = labels.to(device, non_blocking=True)        # [B, 400], dtype long

        # Attention mask: if you have padding/ignored positions -> mask valid tokens
        if ignore_index is not None:
            attention_mask = (labels != ignore_index).long()   # [B, 400]
        else:
            attention_mask = torch.ones_like(labels, dtype=torch.long, device=device)

        optimizer.zero_grad(set_to_none=True)

        # Forward (AMP optional)
        with torch.cuda.amp.autocast(enabled=(use_amp and device.type == "cuda")):
            logits = model(inputs_embeds=inputs74, attention_mask=attention_mask)  # [B, 400, C]

            # Sanity checks (lightweight; you can disable after debugging)
            if logits.dim() != 3:
                raise ValueError(f"Expected logits [B, T, C], got shape {tuple(logits.shape)}")
            B, T, C = logits.shape
            if num_classes is not None and C != num_classes:
                raise ValueError(f"Class count mismatch: logits C={C}, expected {num_classes}")
            if labels.shape != (B, T):
                raise ValueError(f"Labels shape {tuple(labels.shape)} must match [B, T] = ({B}, {T})")

            # Token CE: flatten ([B*T, C], [B*T])
            loss = criterion(logits.view(B * T, C), labels.view(B * T))

        # Backward
        if scaler.is_enabled():
            scaler.scale(loss).backward()
            if grad_clip_norm is not None:
                scaler.unscale_(optimizer)
                torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip_norm)
            scaler.step(optimizer)
            scaler.update()
        else:
            loss.backward()
            if grad_clip_norm is not None:
                torch.nn.utils.clip_grad_norm_(model.parameters(), grad_clip_norm)
            optimizer.step()

        if scheduler is not None:
            scheduler.step()

        # Logging (primary only)
        if is_primary():
            lr = optimizer.param_groups[0]["lr"]
            iterator.set_description(f"epoch: {epoch+1}; loss: {loss.item():.5f}; lr: {lr:.6f}")
            run["transformer/train-loss"].log(loss.item())
            run["transformer/lr"].log(lr)

    # ---------- VALIDATION ----------
    if val_loader is None:
        return None

    val_iter = tqdm(val_loader) if is_primary() else val_loader
    model.eval()  # ALL ranks

    total_loss = 0.0
    total_batches = 0

    with torch.no_grad():
        for vi, (inputs74, labels) in enumerate(val_iter, start=1):
            inputs74 = inputs74.to(device, non_blocking=True)
            labels   = labels.to(device, non_blocking=True)

            if ignore_index is not None:
                attention_mask = (labels != ignore_index).long()
            else:
                attention_mask = torch.ones_like(labels, dtype=torch.long, device=device)

            with torch.cuda.amp.autocast(enabled=(use_amp and device.type == "cuda")):
                logits = model(inputs_embeds=inputs74, attention_mask=attention_mask)  # [B, 400, C]
                B, T, C = logits.shape

                val_loss = criterion(logits.view(B * T, C), labels.view(B * T))

            total_loss += val_loss.item()
            total_batches += 1

            # Log progress every N batches (we still compute every batch for a true mean)
            if is_primary() and (vi % log_every == 0 or vi == 1):
                run["transformer/val-loss"].log(val_loss.item())
                if isinstance(val_iter, tqdm):
                    val_iter.set_description(f"Validation loss: {val_loss.item():.5f}")

    avg_val = total_loss / max(1, total_batches)
    if is_primary():
        run["transformer/val-average_loss_per_epoch"].log(avg_val)
    return avg_val



